func scanTime(dst *time.Time, src any, layouts []string) error {
	switch v := src.(type) {
	case nil:
		*dst = time.Time{}
	case time.Time:
		*dst = v
	case string:
		parsed, err := parseTemporal("time", v, layouts)
		if err != nil {
			return err
		}
		*dst = parsed
	case []byte:
		parsed, err := parseTemporal("time", string(v), layouts)
		if err != nil {
			return err
		}
		*dst = parsed
	default:
		return fmt.Errorf("cannot scan %T into a temporal value", src)
	}
	return nil
}

// Duration is xs:duration, held in its lexical form. It maps to a Postgres
// interval, which -- like XSD and unlike time.Duration -- keeps months
// separate from days.
type Duration string

// ToDuration converts to a time.Duration. Years and months have no fixed
// length, so they are approximated at 365.2425 and 30.436875 days; anything
// that must be exact should apply the calendar fields to a specific date
// instead.
func (d Duration) ToDuration() (time.Duration, error) {
	s := strings.TrimSpace(string(d))
	if s == "" {
		return 0, nil
	}
	neg := false
	if strings.HasPrefix(s, "-") {
		neg, s = true, s[1:]
	}
	if !strings.HasPrefix(s, "P") {
		return 0, fmt.Errorf("duration: %q does not start with P", d)
	}
	s = s[1:]
	var total float64
	inTime := false
	num := ""
	for _, r := range s {
		switch {
		case r == 'T':
			inTime, num = true, ""
		case (r >= '0' && r <= '9') || r == '.':
			num += string(r)
		default:
			v, err := strconv.ParseFloat(num, 64)
			if err != nil {
				return 0, fmt.Errorf("duration: bad value in %q", d)
			}
			num = ""
			day := float64(24 * time.Hour)
			switch {
			case r == 'Y':
				total += v * 365.2425 * day
			case r == 'M' && !inTime:
				total += v * 30.436875 * day
			case r == 'D':
				total += v * day
			case r == 'H':
				total += v * float64(time.Hour)
			case r == 'M' && inTime:
				total += v * float64(time.Minute)
			case r == 'S':
				total += v * float64(time.Second)
			default:
				return 0, fmt.Errorf("duration: unknown designator %q in %q", r, d)
			}
		}
	}
	if num != "" {
		return 0, fmt.Errorf("duration: trailing number in %q", d)
	}
	out := time.Duration(total)
	if neg {
		out = -out
	}
	return out, nil
}

