// goSupportSource renders the runtime support file that accompanies generated
// Go models. It is emitted as source rather than imported from a library so
// the generated package has no dependency outside the standard library: a
// caller can drop the two files into a project and build.
//
// %BT% stands in for a back quote, which cannot appear inside the raw string
// literal that holds the template.
func goSupportSource(pkg string) string {
	s := strings.ReplaceAll(goSupport, "%PACKAGE%", pkg)
	return strings.ReplaceAll(s, "%BT%", "`")
}

