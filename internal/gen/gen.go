// Package gen turns the resolved model into source code. Every generator emits
// plain data classes: fields, no behaviour, and whatever attributes or
// annotations the language's standard XML binding needs, so that deserializing
// a document is one call against a type the caller already has.
package gen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/chriswirz/xsd2code-go/internal/ir"
)

// Options configures a generation run.
type Options struct {
	// Language is one of Languages(); a few common aliases are accepted too.
	Language string
	// Package is the Go package, Java package or C# namespace to emit into.
	Package string
	// Postgres adds persistence mapping to the generated types and emits the
	// DDL alongside them.
	Postgres bool
	// TablePrefix is prepended to every generated table name.
	TablePrefix string
	// Source names the schema files the model came from, for the header
	// comment that tells a reader not to edit the output by hand.
	Source string
	// XmlSerializable selects the second C# format: classes that implement
	// IXmlSerializable with generated readers and writers, so the consuming
	// application serializes without XmlSerializer and therefore without
	// reflection. It is ignored by every other language.
	XmlSerializable bool
}

// File is one generated source file.
type File struct {
	Name    string
	Content []byte
}

// Languages lists the supported --lang values, in the order the help prints
// them.
func Languages() []string {
	return []string{
		"go", "csharp", "java", "kotlin", "swift",
		"typescript", "javascript", "python", "rust", "cpp",
	}
}

// Generate produces the source files for one language.
func Generate(m *ir.Model, o Options) ([]File, error) {
	var rel *ir.Relational
	if o.Postgres {
		rel = ir.Relations(m, o.TablePrefix)
	}

	var files []File
	var err error
	switch strings.ToLower(o.Language) {
	case "go", "golang":
		files, err = genGo(m, rel, o)
	case "cs", "csharp", "c#":
		files, err = genCSharp(m, rel, o)
	case "java":
		files, err = genJava(m, rel, o)
	case "ts", "typescript":
		files, err = genTypeScript(m, rel, o)
	case "js", "javascript":
		files, err = genJavaScript(m, rel, o)
	case "py", "python":
		files, err = genPython(m, rel, o)
	case "rs", "rust":
		files, err = genRust(m, rel, o)
	case "kt", "kotlin":
		files, err = genKotlin(m, rel, o)
	case "swift":
		files, err = genSwift(m, rel, o)
	case "cpp", "c++", "cxx":
		files, err = genCpp(m, rel, o)
	default:
		return nil, fmt.Errorf("unsupported language %q; want one of %s",
			o.Language, strings.Join(Languages(), ", "))
	}
	if err != nil {
		return nil, err
	}
	if rel != nil {
		files = append(files, File{Name: "schema.sql", Content: []byte(genDDL(m, rel, o))})
	}
	return files, nil
}

// buf is a small indent-aware source writer. Templates were tempting here, but
// three languages with different comment, attribute and nesting conventions
// end up clearer written out than expressed as one shared template with a
// dozen conditionals.
type buf struct {
	sb     strings.Builder
	indent int
	pad    string
}

func newBuf(pad string) *buf { return &buf{pad: pad} }

// L writes one indented line, formatting as fmt.Printf does.
func (b *buf) L(format string, args ...any) {
	if format != "" {
		b.sb.WriteString(strings.Repeat(b.pad, b.indent))
		if len(args) == 0 {
			b.sb.WriteString(format)
		} else {
			fmt.Fprintf(&b.sb, format, args...)
		}
	}
	b.sb.WriteString("\n")
}

// In and Out move the indent level.
func (b *buf) In()  { b.indent++ }
func (b *buf) Out() { b.indent-- }

func (b *buf) String() string { return b.sb.String() }
func (b *buf) Bytes() []byte  { return []byte(b.sb.String()) }

// doc emits a documentation comment, wrapped, using the given line prefix. It
// writes nothing for empty text so the output never carries hollow comments.
func (b *buf) doc(prefix, text string) {
	for _, line := range wrap(text, 76) {
		b.L("%s%s", prefix, line)
	}
}

// wrap breaks text into lines of at most width characters. Schema
// documentation is written as one long paragraph far more often than not.
func wrap(text string, width int) []string {
	text = strings.Join(strings.Fields(text), " ")
	if text == "" {
		return nil
	}
	var lines []string
	for len(text) > width {
		cut := strings.LastIndex(text[:width], " ")
		if cut <= 0 {
			cut = width
		}
		lines = append(lines, text[:cut])
		text = strings.TrimSpace(text[cut:])
	}
	return append(lines, text)
}

// header is the banner every generated file opens with.
func header(o Options, comment string) []string {
	src := o.Source
	if src == "" {
		src = "an XML schema"
	}
	return []string{
		comment + " Code generated by xsd2code-go from " + src + ". DO NOT EDIT.",
		comment + "",
		comment + " Regenerate with: xsd2code-go generate --lang " + o.Language + " " + src,
	}
}

// choiceNote describes the mutually exclusive members of a choice so the
// generated comment says what the type system cannot.
func choiceNote(t *ir.Type, group int) string {
	if group == 0 {
		return ""
	}
	var names []string
	for _, f := range t.Fields {
		if f.Choice == group {
			names = append(names, f.Name)
		}
	}
	if len(names) < 2 {
		return ""
	}
	return "Part of a choice: exactly one of " + strings.Join(names, ", ") + " is present."
}

// choiceGroups returns the distinct choice numbers on a type, in order.
func choiceGroups(t *ir.Type) []int {
	seen := map[int]bool{}
	var out []int
	for _, f := range t.Fields {
		if f.Choice != 0 && !seen[f.Choice] {
			seen[f.Choice] = true
			out = append(out, f.Choice)
		}
	}
	sort.Ints(out)
	return out
}

// fieldDoc assembles the comment for a field: the schema's own documentation,
// then the facts the generated declaration cannot show.
func fieldDoc(t *ir.Type, f *ir.Field) string {
	parts := []string{}
	if f.Doc != "" {
		parts = append(parts, f.Doc)
	}
	switch f.Origin {
	case ir.AttributeField:
		parts = append(parts, "XML attribute "+quoteName(f)+".")
	case ir.TextField:
		parts = append(parts, "The element's text content.")
	case ir.AnyField:
		parts = append(parts, "Wildcard element content.")
	case ir.AnyAttrField:
		parts = append(parts, "Wildcard attribute content.")
	}
	if f.List {
		parts = append(parts, "Serialized as a space-separated list.")
	}
	if f.Fixed != "" {
		parts = append(parts, "Fixed value: "+f.Fixed+".")
	} else if f.Default != "" {
		parts = append(parts, "Defaults to "+f.Default+".")
	}
	if note := choiceNote(t, f.Choice); note != "" {
		parts = append(parts, note)
	}
	return strings.Join(parts, " ")
}

func quoteName(f *ir.Field) string {
	if f.Namespace != "" {
		return `"{` + f.Namespace + `}` + f.XMLName + `"`
	}
	return `"` + f.XMLName + `"`
}

// nameSet hands out identifiers unique within one scope, suffixing a number
// when a name is already taken. Two schema members can differ only in
// punctuation and still collide once they are spelled as identifiers.
type nameSet struct{ seen map[string]bool }

func newNames() *nameSet { return &nameSet{seen: map[string]bool{}} }

// has reports whether a name is already claimed.
func (n *nameSet) has(name string) bool { return n.seen[name] }

// reserve claims a name without generating one.
func (n *nameSet) reserve(name string) { n.seen[name] = true }

func (n *nameSet) take(name string) string {
	if name == "" {
		name = "value"
	}
	if !n.seen[name] {
		n.seen[name] = true
		return name
	}
	for i := 2; ; i++ {
		candidate := fmt.Sprintf("%s%d", name, i)
		if !n.seen[candidate] {
			n.seen[candidate] = true
			return candidate
		}
	}
}

// baseFirst orders the types so that a base class always precedes the types
// that extend it. A Python class statement evaluates its base immediately, so
// the model's own order -- which follows the schema -- will not do.
func baseFirst(m *ir.Model) []*ir.Type {
	byName := map[string]*ir.Type{}
	for _, t := range m.Types {
		byName[t.Name] = t
	}
	var out []*ir.Type
	done := map[string]bool{}
	var visit func(t *ir.Type)
	visit = func(t *ir.Type) {
		if t == nil || done[t.Name] {
			return
		}
		// Marked before the recursion, so a base chain that somehow loops back
		// on itself terminates instead of overflowing the stack.
		done[t.Name] = true
		if t.Base != "" {
			visit(byName[t.Base])
		}
		out = append(out, t)
	}
	for _, t := range m.Types {
		visit(t)
	}
	return out
}

// selfReferential finds the types that can reach themselves through
// single-valued content. Rust needs a Box for them and Swift a reference type;
// in both languages a value that contains itself has no size the compiler can
// work out.
func selfReferential(m *ir.Model) map[string]bool {
	// edges[a][b] means a holds a b directly, by value.
	edges := map[string]map[string]bool{}
	for _, t := range m.Types {
		if t.Kind != ir.Class {
			continue
		}
		edges[t.Name] = map[string]bool{}
		if t.Base != "" {
			edges[t.Name][t.Base] = true
		}
		for _, f := range t.Fields {
			if f.TypeName != "" && !f.Repeated && !f.List {
				edges[t.Name][f.TypeName] = true
			}
		}
	}
	out := map[string]bool{}
	for name := range edges {
		if reaches(edges, name, name, map[string]bool{}) {
			out[name] = true
		}
	}
	return out
}

// reaches reports whether from can get to target by value.
func reaches(edges map[string]map[string]bool, from, target string, seen map[string]bool) bool {
	for next := range edges[from] {
		if next == target {
			return true
		}
		if seen[next] {
			continue
		}
		seen[next] = true
		if reaches(edges, next, target, seen) {
			return true
		}
	}
	return false
}
