// genDDL renders the Postgres schema for a model.
//
// Tables come first and every foreign key follows as its own ALTER TABLE.
// Schemas are routinely recursive -- an element that contains itself is
// ordinary -- so there is no ordering of CREATE TABLE statements that would
// let inline REFERENCES clauses all resolve. Adding the constraints afterwards
// sidesteps the question entirely.
func genDDL(m *ir.Model, rel *ir.Relational, o Options) string {
	// A foreign key references whatever the target table calls its key,
	// which is not always "id": a model read from a database keeps the
	// names it found there.
	keyOf := func(table string) string {
		for _, t := range rel.Tables {
			if t.Name == table {
				return t.Key().Name
			}
		}
		return ir.SurrogateKey
	}
	b := newBuf("    ")
	for _, line := range header(o, "--") {
		b.L("%s", line)
	}
	b.L("--")
	b.doc("-- ", "One table per complex type. Inheritance is joined-table: a derived type's primary key is also a foreign key onto its base, so a query against the base sees every descendant. Repeated complex content is joined through a link table, because the same type is often reachable from more than one parent.")
	b.L("")
	b.L("BEGIN;")
	b.L("")

	for _, tbl := range rel.Tables {
		genDDLTable(b, m, tbl)
	}
	for _, tbl := range rel.Tables {
		for _, link := range tbl.Links {
			genDDLLink(b, link)
		}
	}

	b.L("-- Foreign keys. Deleting a document should take its content with it, so")
	b.L("-- every reference from a parent row to owned content cascades.")
	for _, tbl := range rel.Tables {
		if tbl.Parent != "" {
			key := tbl.Key().Name
			b.L("ALTER TABLE %s ADD CONSTRAINT %s", ident(tbl.Name),
				ident(constraintName("fk", tbl.Name, key)))
			b.L("    FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE CASCADE;",
				ident(key), ident(tbl.Parent), ident(keyOf(tbl.Parent)))
		}
		for _, col := range tbl.Columns {
			if col.References == "" {
				continue
			}
			b.L("ALTER TABLE %s ADD CONSTRAINT %s", ident(tbl.Name),
				ident(constraintName("fk", tbl.Name, col.Name)))
			b.L("    FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE CASCADE;",
				ident(col.Name), ident(col.References), ident(keyOf(col.References)))
			b.L("CREATE INDEX IF NOT EXISTS %s ON %s (%s);",
				ident(constraintName("ix", tbl.Name, col.Name)), ident(tbl.Name), ident(col.Name))
		}
		for _, link := range tbl.Links {
			b.L("ALTER TABLE %s ADD CONSTRAINT %s", ident(link.Name),
				ident(constraintName("fk", link.Name, link.ParentColumn)))
			b.L("    FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE CASCADE;",
				ident(link.ParentColumn), ident(link.Parent), ident(keyOf(link.Parent)))
			b.L("ALTER TABLE %s ADD CONSTRAINT %s", ident(link.Name),
				ident(constraintName("fk", link.Name, link.ChildColumn)))
			b.L("    FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE CASCADE;",
				ident(link.ChildColumn), ident(link.Child), ident(keyOf(link.Child)))
		}
	}

	b.L("")
	b.L("COMMIT;")
	return b.String()
}

// genDDLTable writes the CREATE TABLE for one class.
func genDDLTable(b *buf, m *ir.Model, tbl *ir.Table) {
	if tbl.Doc != "" {
		b.doc("-- ", tbl.Doc)
	} else if tbl.Type.XMLName != "" {
		b.L("-- Stores the %q complex type.", tbl.Type.XMLName)
	}
	if tbl.Type.Abstract {
		b.L("-- The schema marks this type abstract; rows exist only through a derived table.")
	}
	b.L("CREATE TABLE IF NOT EXISTS %s (", ident(tbl.Name))
	b.In()

	lines := make([]string, 0, len(tbl.Columns))
	for _, col := range tbl.Columns {
		var sb strings.Builder
		sb.WriteString(ident(col.Name) + " " + col.SQLType)
		if col.PrimaryKey {
			if !tbl.Surrogate {
				// A key the model carries is written by the caller, not
				// generated, and an identity column would fight it.
				sb.WriteString(" PRIMARY KEY")
			} else if tbl.Parent == "" {
				// An identity column rather than bigserial: it is the standard
				// spelling, and it refuses an accidental explicit insert unless
				// the caller asks for one.
				sb.WriteString(" GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
			} else {
				// A derived table's key is supplied by its base row.
				sb.WriteString(" PRIMARY KEY")
			}
		} else {
			if col.NotNull {
				sb.WriteString(" NOT NULL")
			}
			if def := sqlDefault(m, col); def != "" {
				sb.WriteString(" DEFAULT " + def)
			}
			if col.Check != "" {
				sb.WriteString(" CONSTRAINT " + ident(constraintName("ck", tbl.Name, col.Name)) +
					" CHECK (" + col.Check + ")")
			}
		}
		lines = append(lines, sb.String())
	}
	for i, line := range lines {
		comma := ","
		if i == len(lines)-1 {
			comma = ""
		}
		b.L("%s%s", line, comma)
	}
	b.Out()
	b.L(");")
	genDDLComments(b, tbl)
	b.L("")
}

// genDDLComments carries the schema's own documentation into the database, so
// psql \d+ and every introspection tool show what the column meant in the XML.
func genDDLComments(b *buf, tbl *ir.Table) {
	if tbl.Doc != "" {
		b.L("COMMENT ON TABLE %s IS %s;", ident(tbl.Name), literal(tbl.Doc))
	}
	for _, col := range tbl.Columns {
		note := col.Doc
		if col.Field != nil {
			if origin := originNote(col.Field); origin != "" {
				if note != "" {
					note += " "
				}
				note += origin
			}
		}
		if note != "" {
			b.L("COMMENT ON COLUMN %s.%s IS %s;", ident(tbl.Name), ident(col.Name), literal(note))
		}
	}
}

// originNote records where in the document the column's value came from, which
// is the one thing a reader of the database cannot otherwise recover.
func originNote(f *ir.Field) string {
	switch f.Origin {
	case ir.AttributeField:
		return "From XML attribute " + quoteName(f) + "."
	case ir.TextField:
		return "From the element's text content."
	case ir.AnyField:
		return "From wildcard element content."
	case ir.AnyAttrField:
		return "Undeclared attributes, as a JSON object."
	}
	if f.XMLName != "" {
		return "From XML element " + quoteName(f) + "."
	}
	return ""
}

// genDDLLink writes an association table for a repeated complex field.
func genDDLLink(b *buf, link *ir.LinkTable) {
	b.L("-- Joins %s to the %s rows of its repeated %q content.",
		ident(link.Parent), ident(link.Child), link.Field.XMLName)
	b.L("CREATE TABLE IF NOT EXISTS %s (", ident(link.Name))
	b.In()
	b.L("%s %s NOT NULL,", ident(link.ParentColumn), sqlTypeOr(link.ParentType))
	b.L("%s %s NOT NULL,", ident(link.ChildColumn), sqlTypeOr(link.ChildType))
	// Document order is part of the data: <item>a</item><item>b</item> is not
	// the same document as the reverse, and a set of rows has no order at all.
	b.L("ordinal integer NOT NULL,")
	b.L("PRIMARY KEY (%s, ordinal)", ident(link.ParentColumn))
	b.Out()
	b.L(");")
	b.L("CREATE INDEX IF NOT EXISTS %s ON %s (%s);",
		ident(constraintName("ix", link.Name, link.ChildColumn)), ident(link.Name), ident(link.ChildColumn))
	b.L("")
}

// sqlDefault renders a schema default or fixed value as a SQL literal.
func sqlDefault(m *ir.Model, col *ir.Column) string {
	f := col.Field
	if f == nil || col.References != "" {
		return ""
	}
	v := f.Default
	if f.Fixed != "" {
		v = f.Fixed
	}
	if v == "" || f.Repeated || f.List {
		return ""
	}
	if f.TypeName == "" && (f.Builtin.Numeric() || f.Builtin == ir.Bool) {
		// A numeric or boolean literal is written bare; anything else is
		// quoted and cast, which is what makes a default valid on a text,
		// timestamptz or interval column alike.
		return v
	}
	return literal(v) + "::" + strings.TrimSuffix(col.SQLType, "[]")
}

// ident quotes an identifier. Everything is quoted: it costs nothing and it
// removes any question of what happens to a name that collides with a keyword
// a future Postgres release introduces.
func ident(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `""`) + `"`
}

// literal quotes a string value.
func literal(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

// constraintName builds a constraint or index name inside Postgres's 63-byte
// identifier limit, trimming the table name first because the column is the
// part that distinguishes one constraint on a table from another.
func constraintName(kind, table, column string) string {
	const max = 63
	name := fmt.Sprintf("%s_%s_%s", kind, table, column)
	if len(name) <= max {
		return name
	}
	room := max - len(kind) - len(column) - 2
	if room < 1 {
		return name[:max]
	}
	return fmt.Sprintf("%s_%s_%s", kind, table[:room], column)
}

// sqlTypeOr defaults a key type that was never filled in, which happens only
// for a link whose target is missing from the model.
func sqlTypeOr(t string) string {
	if t == "" {
		return "bigint"
	}
	return t
}
